@torch.no_grad()
def classify_images_with_qwen(
    images,
    zeroshot_weights,
    qwen_model,
):
    qwen_model.model.to("cuda")
    qwen_model.model.eval()

    image_features = get_image_embedding(
        qwen_model,
        images
    )
    image_features = F.normalize(
        image_features,
        dim=-1
    )

    qwen_model.model.to("cpu")
    torch.cuda.empty_cache()

    # Normalized image and text embeddings -> cosine similarity
    similarities = (
        image_features.to(zeroshot_weights.dtype)
        @ zeroshot_weights.T
    )

    predicted_classes = similarities.argmax(dim=-1)

    return predicted_classes, similarities

