def caption_image(
    images_path,
    class_name,
    llava_tokenizer,
    llava_model,
    llava_processor,
):
    query = (
        f"Provide a detailed caption for the image focusing on the object, "
        f"knowing it's a {class_name}."
    )

    batch_images, batch_text = (
        llava_processor.get_processed_tokens_batch(
            [query] * len(images_path),
            images_path,
        )
    )

    conv = conv_templates[llava_processor.conv_mode].copy()
    stop_str = (
        conv.sep
        if conv.sep_style != SeparatorStyle.TWO
        else conv.sep2
    )

    input_ids = batch_text.cuda()

    with torch.inference_mode():
        output_ids = llava_model.generate(
            input_ids,
            images=batch_images.half().cuda(),
            do_sample=True,
            temperature=0.2,
            max_new_tokens=1024,
            use_cache=True,
        )

    outputs = llava_tokenizer.batch_decode(
        output_ids[:, input_ids.shape[1]:],
        skip_special_tokens=True,
    )

    outputs = [x.strip() for x in outputs]
    outputs = [
        x[:-len(stop_str)] if x.endswith(stop_str) else x
        for x in outputs
    ]

    return [x.strip() for x in outputs]

