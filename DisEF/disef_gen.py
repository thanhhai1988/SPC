@torch.no_grad()
def build_qwen_zeroshot_weights(
    dataset,
    class_names,
    qwen_model,
):
    dataset_name = get_dataset_name_for_template(dataset)
    prototypes = []

    qwen_model.model.to("cuda")
    qwen_model.model.eval()

    for class_name in class_names:
        class_texts = [
            {
                "text": template.format(
                    dataset_name,
                    class_name
                ) + "."
            }
            for template in TEMPLATES_SMALL
        ]

        class_embs = qwen_model.process(class_texts)
        class_embs = F.normalize(class_embs, dim=-1)

        prototype = class_embs.mean(dim=0)
        prototype = F.normalize(prototype, dim=-1)

        prototypes.append(prototype)

    weights = torch.stack(prototypes)

    qwen_model.model.to("cpu")
    torch.cuda.empty_cache()

    return weights

